Původ je to, co tvoje postava dělala před dobrodružstvím. Jako v 5E, ale **bez zdatností v dovednostech**: ty pocházejí z povolání. Dává počáteční výbavu, mince a Materiál, [jazyky](languages) navíc a jedno známé prostředí.

## Štěstí {#fortune}

Jak se postavě dosud vedlo, se řekne ve třech částech: **zbraně a zbroj**, **původ** a **kůň**. U každé řekneš, jestli byla **chudá**, **prostá**, nebo **zámožná**. Možnosti rozdává počáteční úroveň a ty volíš, kam která půjde.

| Začátek | Možnosti k rozdělení |
|---|---|
| Z hadrů do zlata (3) | Prostý, prostý, chudý |
| Ostřílený (7) | Zámožný, prostý, chudý |
| Veterán (9) | Zámožný, prostý, prostý |

Nic z toho se nevyvažuje ve stříbře. Válečný kůň má větší cenu než meč a meč větší než stan, ale co uděláš zámožným, nemůžeš udělat zámožným jinde. Jezdec, který vsadí své štěstí na válečného koně, jde do války v prošívanici.

:::example[Kam šlo štěstí]{image="/img/rulebook/michal.webp"}
Michal začíná jako Ostřílený: zámožný, prostý, chudý. Chce vypadat jako rytíř, takže zbraně a zbroj dostanou *zámožný*: dlouhý meč, štít a kroužkovou košili. Kůň dostane *prostý*, obyčejného jezdeckého koně. Na původ zbývá *chudý*: Voják, odvedenec poslaný domů, s batohem, spací rohoží a 10 stříbrnými.
:::

## Zbraně a zbroj {#arms-and-armour}

Pro každý původ stejné. K luku, kuši nebo praku patří toulec a 20 kusů střeliva.

| Štěstí | Zbraně | Zbroj |
|---|---|---|
| **Chudý** | Jedna zbraň, žádné meče | Prošívaná kápě, nebo prošívanice |
| **Prostý** | Dvě zbraně, nebo zbraň a štít; žádné meče | Lehká: Ochrana nejvýš 3 |
| **Zámožný** | Dvě zbraně, nebo zbraň a štít; meče povoleny | Nejvýš střední: Ochrana nejvýš 6 |

:::note[Meče se neprodávají]
Meč má cenu malého jmění, ale kolik stojí, zaplatí jen rytíř, šlechtic nebo zbrojíř. Obyčejní řemeslníci ti dají za jeho železo zhruba desetinu ceny, v Materiálu nebo v mincích.
:::

## Původ {#the-background}

Každý původ má tři podoby, jednu pro každé štěstí: odvedenec poslaný domů i seržant jsou vojáci, ale nenosí totéž. Podoba dává výbavu, mince a Materiál.

## Kůň {#mount}

Chudá postava chodí pěšky. Prostá má **jezdeckého koně** s postrojem, zámožná **válečného koně**, cvičeného, aby se nesplašil před ocelí ani ohněm.

## Naložení a oblečení {#load-and-clothes}

Oblečení nejsou předměty: na deník napíšeš, co má postava na sobě.

Naložení se posuzuje od oka. Porovnej postavu se třemi siluetami: lehké (oblečení a osobní věci), střední (víc než pár brašen) a těžké (těžká krosna s věcmi zavěšenými na ní, štít a dva meče). Střední naložení stojí jako střední zbroj, 1 :body[Tělo] za pokus u činností, které omezuje; těžké stojí 2, jako těžká zbroj. Počítá se jen horší z naložení a zbroje.

![Lehké, střední a těžké naložení](/img/rulebook/load.png)

Kůň nese náklad, ale jen dokud je u tebe. Necháš-li většinu věcí na koni před jeskyní, raději ho schovej, jinak s nimi odjede někdo jiný.

## Rychlý začátek {#jumpstart}

Každý původ má tabulky k8 s **archetypy**, **zvláštnostmi**, **ideály**, **pouty** a **chybami**, od kterých se dá odrazit. Hoď nebo vyber, co se ti líbí, opiš do povahy a příběhu, nebo je přeskoč. Archetyp navíc doporučuje výbavu, ale nic tě k ní nezavazuje. Každá tabulka má devátý řádek: vymysli si vlastní.

## Známá prostředí {#known-settings}

Hod uvnitř známého prostředí původu dostane **+1**. Platí jen pro hody na :soul[Duši] a :charisma[Vliv] (vyznat se, najít toho správného člověka, smlouvat, dostat slyšení), pro každý druh hodu a i bez vhodného povolání: holé 2k6 + 1. O tom, jestli hod do prostředí spadá, rozhoduje PJ.

:::example[Smlouvání s proviantníkem]{image="/img/rulebook/michal.webp"}
Michal, bývalý Voják, smlouvá s táborovým proviantníkem o koně. Vojenské tábory jsou jeho známé prostředí: +1 navíc k úrovni Kejklíře.

Proviantník ho stejně ošidí, jen míň.
:::

