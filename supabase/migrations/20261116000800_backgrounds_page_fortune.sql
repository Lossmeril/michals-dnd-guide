update public.rulebook_pages set content = $md$A background is what your character did before the adventure. Like in 5E, but **without skill proficiencies**: those come from classes. It gives starting gear, coins and Material, extra [languages](languages), and one known setting.

## Fortune

How well your character has done so far is told in three parts: their **arms and armour**, their **background**, and a **mount**. For each one you say whether they've been **poor**, a **commoner** or **fortunate**. Your starting level hands out the fortunes, and you choose where each one goes.

| Start | Fortunes to give out |
|---|---|
| Rags to Riches (3) | Commoner, commoner, poor |
| Seasoned (7) | Fortunate, commoner, poor |
| Veteran (9) | Fortunate, commoner, commoner |

Nothing here is balanced in silver. A warhorse is worth more than a sword, and a sword more than a tent, but whatever you make fortunate you can't make fortunate elsewhere. A rider who spends their luck on a warhorse goes to war in a padded coat.

:::example[Where the luck went]{image="/img/rulebook/michal.webp"}
Michal starts Seasoned: fortunate, commoner, poor. He wants a knight's look, so arms and armour get *fortunate*: a longsword, a shield and a mail shirt. The mount gets *commoner*, a plain riding horse. That leaves *poor* for his background: the Soldier's levy sent home, with a backpack, a bedroll and 10 silver.
:::

## Arms and armour

The same for every background. A bow, crossbow or sling comes with its quiver and 20 pieces of ammunition.

| Fortune | Weapons | Armour |
|---|---|---|
| **Poor** | One weapon, no swords | A padded hood or a gambeson |
| **Commoner** | Two weapons, or a weapon and a shield; no swords | Light: Protection up to 3 |
| **Fortunate** | Two weapons, or a weapon and a shield; swords allowed | Up to medium: Protection up to 6 |

:::note[Swords don't sell]
A sword is worth a fortune, but only a knight, a noble or an armourer will pay what it's worth. Ordinary tradespeople give you its iron, about a tenth of the price, in Material or coin.
:::

## The background

Each background comes in three versions, one for each fortune: a levy sent home and a sergeant are both soldiers, but they don't carry the same things. The version gives the gear, the coins and the Material.

## Mount

A poor character walks. A commoner has a **riding horse** with tack; a fortunate one a **warhorse**, trained not to bolt at steel or fire.

## Load and clothes

Clothes aren't items: you write on the sheet what your character wears.

Load is judged by eye. Compare your character with the three silhouettes: light (clothes and personal things), medium (more than a couple of bags) and heavy (a heavy pack with things hung on it, a shield and two swords). Carrying a medium load costs what medium armour does, 1 :body to attempt the activities it hinders; a heavy load costs 2, like heavy armour. Only the worse of load and armour counts.

![Light, medium and heavy load](/img/rulebook/load.png)

A mount carries the load, but only while it's there. Leave most of your things on the horse outside the dungeon, and you'd better hide it, or someone else will ride off with them.

## Jumpstart

Every background has d8 tables of **archetypes**, **quirks**, **ideals**, **bonds** and **flaws** to start from. Roll or pick, copy what you like into the personality and backstory, or ignore them. An archetype also recommends picks, but nothing obliges you to follow them. Each table has a ninth line: make up your own.

## Known settings

A roll inside the background's known setting gets **+1**. It applies only to :soul and :charisma rolls (knowing the ropes, finding the right person, haggling, getting a hearing), to every kind of roll, and without a fitting class too: a plain 2d6 + 1. The DM decides whether a roll falls inside the setting.

:::example[Haggling with a quartermaster]{image="/img/rulebook/michal.webp"}
Michal, a former Soldier, haggles with a camp quartermaster over a horse. War camps are his known setting: +1 on top of his Juggler level.

The quartermaster still cheats him, just less.
:::

