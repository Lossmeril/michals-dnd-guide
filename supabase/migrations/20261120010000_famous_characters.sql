Nevíš, co hrát? Najdi si níže postavu, která se ti líbí, a podívej se, z jakých povolání by byla složená. Jsou to hrubé odhady, ne přesné buildy: vezmi si, co tě láká, a zbytek nech být.

Většina hrdinů potřebuje víc než jedno povolání. Postava začíná jedním nebo dvěma základními povoláními a pokročilá a mocná přijdou později, jak postupuje na další úrovně.

