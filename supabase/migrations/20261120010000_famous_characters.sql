## Mocná povolání {#mighty-classes}

Legendy: vládci, netvoři v lidské kůži a mistři magie. Někteří začínají v pokročilém povolání a do mocného dorostou.

::::famous
:::character[Tywin Lannister]{from="Píseň ledu a ohně" classes="Vojevůdce"}
